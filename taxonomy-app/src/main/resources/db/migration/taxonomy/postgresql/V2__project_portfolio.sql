create table if not exists project_solution (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    solution_id bigint not null,
    status varchar(32) not null,
    action_status varchar(32) not null,
    priority integer not null,
    rationale varchar(2000),
    created_by varchar(160) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    row_version bigint not null,
    constraint uq_psol_project_sol unique (project_id, solution_id),
    foreign key (project_id) references arch_project (id),
    foreign key (solution_id) references solution_definition (id)
);
create index if not exists idx_psol_project on project_solution (project_id);
create index if not exists idx_psol_status on project_solution (project_id, status);

create table if not exists req_solution_link (
    id bigint generated by default as identity primary key,
    project_solution_id bigint not null,
    requirement_id bigint not null,
    snapshot_id varchar(36),
    coverage_percent integer not null,
    solution_role varchar(32) not null,

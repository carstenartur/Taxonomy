create table if not exists solution_product (
    id bigint generated by default as identity primary key,
    project_solution_id bigint not null,
    product_id bigint not null,
    coverage_percent integer not null,
    hard_exclusions varchar(4000),
    strengths varchar(4000),
    weaknesses varchar(4000),
    open_evidence varchar(4000),
    confidence float(53) not null,
    review_status varchar(32) not null,
    selection_status varchar(32) not null,
    updated_by varchar(160) not null,
    updated_at timestamp(6) with time zone not null,
    row_version bigint not null,
    constraint uq_solprod_pair unique (project_solution_id, product_id),

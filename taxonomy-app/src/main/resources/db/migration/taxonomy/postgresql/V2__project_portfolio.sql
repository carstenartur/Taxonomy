create index if not exists idx_solprod_psol on solution_product (project_solution_id);
create index if not exists idx_solprod_product on solution_product (product_id);

create table if not exists project_conflict (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    requirement_a_id bigint not null,
    requirement_b_id bigint not null,
    conflict_type varchar(32) not null,
    status varchar(32) not null,
    fingerprint varchar(64) not null,
    title varchar(500) not null,
    evidence oid not null,
    confidence float(53) not null,
    resolution_note varchar(4000),
    detected_at timestamp(6) with time zone not null,
    reviewed_by varchar(160),
    reviewed_at timestamp(6) with time zone,
    row_version bigint not null,
    constraint uq_conf_signature unique (project_id, requirement_a_id, requirement_b_id, conflict_type, fingerprint),
    foreign key (project_id) references arch_project (id),
    foreign key (requirement_a_id) references project_requirement (id),
    foreign key (requirement_b_id) references project_requirement (id)
);
create index if not exists idx_conf_project on project_conflict (project_id, status);
create index if not exists idx_conf_req_a on project_conflict (requirement_a_id);
create index if not exists idx_conf_req_b on project_conflict (requirement_b_id);


    decision_by varchar(160),
    decision_at timestamp(6) with time zone,
    decision_comment varchar(2000),
    row_version bigint not null,
    constraint uq_elmap_snap_node unique (snapshot_id, node_code),
    foreign key (snapshot_id) references req_analysis_snapshot (id)
);
create index if not exists idx_elmap_snapshot on req_element_mapping (snapshot_id);
create index if not exists idx_elmap_node on req_element_mapping (node_code);
create index if not exists idx_elmap_action on req_element_mapping (action_status);

create table if not exists req_relation_mapping (
    id bigint generated by default as identity primary key,
    snapshot_id varchar(36) not null,
    source_code varchar(80) not null,
    target_code varchar(80) not null,
    relation_type varchar(64) not null,
    relation_origin varchar(64) not null,

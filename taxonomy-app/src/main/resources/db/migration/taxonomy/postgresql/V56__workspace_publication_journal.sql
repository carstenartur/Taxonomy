-- An operation outlives its working copy. Audit rows retain the original actor independently of the claim owner.
create table workspace_publication_operation (
    operation_id varchar(64) primary key,
    causation_id varchar(64) not null,
    actor_id varchar(64) not null,
    actor_scope varchar(255) not null,
    login_kind varchar(12) not null,
    binding_key varchar(64) not null,
    policy_code varchar(48) not null,
    repository_id varchar(255) not null,
    workspace_id varchar(255) not null,
    local_branch varchar(255) not null,
    source_branch varchar(255) not null,
    keep_workspace boolean not null,
    fork_point varchar(40), input_source varchar(40), input_local varchar(40), input_tracking varchar(40),
    expected_local varchar(40), expected_tracking varchar(40),
    central_portfolio_digest varchar(64), local_portfolio_digest varchar(64),
    merged_digest varchar(64), prepared_source varchar(40), prepared_local varchar(40), prepared_tracking varchar(40),
    phase varchar(24) not null, operation_step varchar(28) not null, attempts integer not null,
    created_at bigint not null, last_attempt_at bigint, next_attempt_at bigint, published_at bigint,
    source_observed_at bigint, pins_released_at bigint, cleanup_due_at bigint, redacted_at bigint,
    completed_at bigint, archived_at bigint, archived_by varchar(64), executor_id varchar(64),
    lease_id varchar(36), decision_code varchar(40)
);
create index ix_ws_publish_due on workspace_publication_operation(phase,next_attempt_at);
create index ix_ws_publish_archive on workspace_publication_operation(archived_at,completed_at);
create index ix_ws_publish_cleanup on workspace_publication_operation(cleanup_due_at,operation_id);
create table workspace_publication_decision (
    id bigint generated by default as identity primary key,
    operation_id varchar(64) not null, original_actor varchar(64) not null, executor_id varchar(64) not null,
    phase_code varchar(28) not null, decision_code varchar(48) not null, decision_at bigint not null
);
create index ix_ws_publish_decision on workspace_publication_decision(operation_id,id);

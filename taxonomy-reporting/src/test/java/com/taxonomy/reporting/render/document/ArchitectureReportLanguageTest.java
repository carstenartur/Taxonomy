package com.taxonomy.reporting.render.document;

import com.taxonomy.dto.*;
import com.taxonomy.extension.api.report.ReportRenderContext;
import org.apache.poi.xwpf.extractor.XWPFWordExtractor;
import org.apache.poi.xwpf.usermodel.XWPFDocument;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class ArchitectureReportLanguageTest {
    @Test void markdownLinksKeepInheritedForegroundAndUnderlineOnDarkPaperAndLightPanels() {
        var report = new ArchitectureReport();
        report.setBusinessText("""
                [Original requirement link](https://example.invalid/requirement)

                | Name | Evidence |
                |---|---|
                | First | Original evidence |
                | Second | [Original panel link](https://example.invalid/evidence) |
                """);
        var theme = com.taxonomy.export.ExportTheme.fromStylesheet("""
                :root{--taxonomy-surface-background:#102030;--taxonomy-panel-background:#fff}
                """);
        String html = new ArchitectureReportTextRenderer(() -> theme).renderHtml(report);
        assertThat(html).contains("html,body{background:#102030;color:#FFFFFF}",
                "{background:#FFFFFF;color:#17212B}",
                "<a href=\"https://example.invalid/requirement\">Original requirement link</a>",
                "<td><a href=\"https://example.invalid/evidence\">Original panel link</a></td>",
                "a:link,a:visited{color:inherit;text-decoration:underline}");
    }

    @Test void boldTableEvidenceInheritsItsPanelForegroundWhenCustomerPaperIsDark() {
        var report = new ArchitectureReport();
        report.setBusinessText("""
                Original requirement.

                | Name | Evidence |
                |---|---|
                | First | Original evidence |
                | Second | **BOLD-CONTEXT-END** |
                """);
        var theme = com.taxonomy.export.ExportTheme.fromStylesheet("""
                :root{--taxonomy-surface-background:#102030;--taxonomy-panel-background:#fff}
                """);
        String html = new ArchitectureReportTextRenderer(() -> theme).renderHtml(report);
        assertThat(html).contains("html,body{background:#102030;color:#FFFFFF}",
                "<td><strong>BOLD-CONTEXT-END</strong></td>", "td strong{color:inherit}");
    }

    @Test void liveWordAndTextUseGermanLabelsWithoutTranslatingRecordedReasons() throws Exception {
        var report = new ArchitectureReport();
        report.setBusinessText("A recorded requirement in its original language.");
        report.setScores(Map.of("CP", 100d));
        var recommendation = new ArchitectureRecommendation();
        recommendation.setReasoning(List.of("An unchanged original explanation. ORIGINAL-ENGLISH-END-7319"));
        report.setRecommendation(recommendation);
        String nodeReason = "The recorded reason remains in its original language. ".repeat(80) + "LIVE-NODE-REASON-END-721";
        var context = new ReportRenderContext(report, Map.of("language", "de", "nodeReasons", Map.of("CP", nodeReason)));
        String markdown = new String(new MarkdownReportRendererExtension(new ArchitectureReportTextRenderer())
                .render(context).bytes(), StandardCharsets.UTF_8);
        String html = new String(new HtmlReportRendererExtension(new ArchitectureReportTextRenderer())
                .render(context).bytes(), StandardCharsets.UTF_8);
        byte[] bytes = new DocxReportRendererExtension(new ArchitectureReportDocxRenderer()).render(context).bytes();
        try (var document = new XWPFDocument(new ByteArrayInputStream(bytes))) {
            String word = new XWPFWordExtractor(document).getText();
            for (String visible : List.of(markdown, html, word)) {
                assertThat(visible).contains("Architekturbericht", "Zugrunde liegende Anforderung",
                        "Empfehlung aus gespeicherter Evidenz", "ORIGINAL-ENGLISH-END-7319", nodeReason)
                        .doesNotContain("Ad-hoc report", "Detected patterns", "Generated by Taxonomy");
            }
        }
        assertThat(html).contains("<html lang=\"de\">");
    }
}

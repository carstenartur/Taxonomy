-- Existing installation-only records have no provable owner and stay in requirement_coverage.
create table scoped_requirement_coverage (
    id bigint generated by default as identity primary key,
    repository_id varchar(255) not null,
    workspace_id varchar(255),
    workspace_scope varchar(257) not null,
    branch_name varchar(255) not null,
    source_commit varchar(40) not null,
    recorded_by varchar(255) not null,
    requirement_id varchar(255) not null,
    requirement_text varchar(2000),
    node_code varchar(255) not null,
    score double precision not null,
    analyzed_at timestamp(6) not null,
    constraint uq_scoped_requirement_coverage unique (repository_id, workspace_scope, branch_name, source_commit, requirement_id, node_code),
    constraint ck_scoped_requirement_owner check (
        (workspace_id is null and workspace_scope='C') or
        (workspace_id is not null and workspace_scope='W:' || workspace_id))
);
